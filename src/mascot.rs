/// Renders the Full-TUI Riverflow Background Watermark with regional gaze, blink, and spell-focus rigging.
pub fn render_background_watermark_with_state(
    buf: &mut ratatui::buffer::Buffer,
    area: Rect,
    anim_elapsed: Duration,
    state: MascotAnimState,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) {
    if area.width < 10 || area.height < 6 {
        return;
    }
    let is_mono = mono || theme.mono;
    let can_animate = animations_enabled && !is_mono && !anim_elapsed.is_zero();
    let elapsed_ms = anim_elapsed.as_millis() as u64;
    let now_ms = anim_elapsed.as_secs_f32() * 1000.0;

    let flow_speed = 0.16_f32;
    let flow_frequency = 0.28_f32;
    let flow_strength_sub = 0.65_f32;
    let direction_x = (18.0_f32.to_radians()).cos();
    let direction_y = (18.0_f32.to_radians()).sin();

    let target_cols = area.width as usize;
    let target_rows = area.height as usize;
    let muted_rgb = extract_rgb(theme.muted, (122, 114, 166));
    let border_rgb = extract_rgb(theme.active_border, (124, 106, 242));
    let is_blinking = can_animate && is_mascot_blinking(elapsed_ms, state.reaction);
    let has_gaze_offset = can_animate && (state.gaze_x.abs() > 0.02 || state.gaze_y.abs() > 0.02);
    let pupil_col = (37.0 + state.gaze_x * 1.8).round() as usize;
    let pupil_row = (6.5 + state.gaze_y * 0.9).round().clamp(5.0, 8.0) as usize;

    let right_edge = area.x.saturating_add(area.width);
    for y in area.y..area.y.saturating_add(area.height) {
        let row_blank: Vec<bool> = (area.x..right_edge)
            .map(|cx| {
                buf.cell((cx, y))
                    .is_some_and(|c| c.symbol() == " " && c.bg == Color::Reset)
            })
            .collect();

        let row = (y - area.y) as usize;
        let mapped_row = (row * 32) / target_rows.max(1);
        for x in area.x..right_edge {
            // Keep a 2-column breathing margin around any foreground text, border, or highlighted row
            // so spaces between words and adjacent to borders remain 100% untouched.
            let x_min = x.saturating_sub(2).max(area.x);
            let x_max = (x + 2).min(right_edge.saturating_sub(1));
            if !(x_min..=x_max).all(|nx| row_blank[(nx - area.x) as usize]) {
                continue;
            }
            let Some(cell) = buf.cell_mut((x, y)) else {
                continue;
            };

            let col = (x - area.x) as usize;
            let mapped_col = (col * 80) / target_cols.max(1);
            let in_face = (5..=8).contains(&mapped_row) && (34..=41).contains(&mapped_col);
            let in_spell_focus = (5..=14).contains(&mapped_row) && (62..=76).contains(&mapped_col);

            let mut sub_shift_x = 0.0_f32;
            let mut sub_shift_y = 0.0_f32;
            let mut wave_mod = 0.0_f32;

            if can_animate {
                let phase = (col as f32 * direction_x + row as f32 * 2.0 * direction_y)
                    * flow_frequency
                    + now_ms * flow_speed * std::f32::consts::PI * 0.002;
                let drift = phase.sin() * flow_strength_sub;
                sub_shift_x -= direction_x * drift;
                sub_shift_y -= (direction_y * drift) * 0.5;
                wave_mod = phase.sin() * 0.08;

                if in_face {
                    sub_shift_x -= state.gaze_x * 2.2;
                    sub_shift_y -= state.gaze_y * 1.8;
                }
                if in_spell_focus {
                    sub_shift_y += (now_ms * 0.0042).sin() * 2.0;
                    if matches!(
                        state.reaction,
                        MascotReaction::Casting | MascotReaction::Refreshing
                    ) {
                        sub_shift_y -= (state.reaction_progress * std::f32::consts::PI).sin() * 2.8;
                        wave_mod += 0.20;
                    }
                }
            }

            let (sr, sg, sb, mut ch) = sample_braille_cell(
                &RIVERFLOW_BRAILLE_80X32,
                col,
                row,
                target_cols,
                target_rows,
                sub_shift_x,
                sub_shift_y,
            );
            if ch == ' ' {
                continue;
            }
            if can_animate && in_face {
                if is_blinking && mapped_row == 6 && (35..=39).contains(&mapped_col) {
                    ch = '\u{2812}';
                } else if has_gaze_offset && mapped_col == pupil_col && mapped_row == pupil_row {
                    ch = carve_gaze_pupil_in_braille(ch, state.gaze_x, state.gaze_y);
                }
            }

            let mut buf_char = [0u8; 4];
            let sym = ch.encode_utf8(&mut buf_char);
            cell.set_symbol(sym);
            if is_mono {
                cell.set_style(Style::default().add_modifier(Modifier::DIM));
            } else {
                // Dual-Layer Shading (Layer A): soft dimmed theme-tinted blend with 25% source RGB
                let raw_lum =
                    (sr as f32 * 0.2126 + sg as f32 * 0.7152 + sb as f32 * 0.0722) / 255.0;
                let value = (raw_lum * 0.75 + wave_mod).clamp(0.0, 0.90);
                let tr = lerp_u8(muted_rgb.0, border_rgb.0, value * 0.70);
                let tg = lerp_u8(muted_rgb.1, border_rgb.1, value * 0.70);
                let tb = lerp_u8(muted_rgb.2, border_rgb.2, value * 0.70);
                let r = lerp_u8(tr, sr, 0.25);
                let g = lerp_u8(tg, sg, 0.25);
                let b = lerp_u8(tb, sb, 0.25);
                cell.set_style(
                    Style::default()
                        .fg(Color::Rgb(r, g, b))
                        .add_modifier(Modifier::DIM),
                );
            }
        }
    }
}

const ARCANE_RING_RUNES: [&str; 12] = ["ᚱ", "✦", "ᛟ", "✧", "ᛉ", "⟡", "ᛞ", "⋆", "ᛇ", "⟐", "ᚨ", "◈"];

const ARCANE_MOTE_GLYPHS: [&str; 8] = ["·", "∙", "✧", "⋆", "✦", "⊹", "ᚱ", "ᛟ"];

/// Generates animated concentric arcane rune circles, celestial ley lines, and drifting
/// mana motes across unoccupied sky/margin cells in the full-screen Background Showcase (`b`).
#[allow(clippy::too_many_arguments)]
fn sample_arcane_backdrop_cell(
    x: u16,
    y: u16,
    area: Rect,
    now_ms: f32,
    state: MascotAnimState,
    can_animate: bool,
    is_mono: bool,
    theme: &Theme,
) -> Option<(&'static str, Style)> {
    let parallax_x = if can_animate { state.gaze_x * 1.5 } else { 0.0 };
    let parallax_y = if can_animate { state.gaze_y * 0.8 } else { 0.0 };
    let cx = area.x as f32 + (area.width.saturating_sub(1) as f32) * 0.5 - parallax_x;
    let cy = area.y as f32 + (area.height.saturating_sub(1) as f32) * 0.5 - parallax_y;
    let scale = (area.height as f32).max(16.0);
    // Aspect-corrected normalized coordinates around center
    let nx = (x as f32 - cx) / (scale * 2.05);
    let ny = (y as f32 - cy) / scale;
    let radius = nx.hypot(ny);
    let angle = ny.atan2(nx);

    let muted_rgb = extract_rgb(theme.muted, (122, 114, 166));
    let border_rgb = extract_rgb(theme.active_border, (124, 106, 242));
    let accent_rgb = extract_rgb(theme.accent, (244, 185, 66));
    let warn_rgb = extract_rgb(theme.warning, (245, 158, 11));

    // Expanding radial mana-ripple wave on Casting or Refreshing
    if can_animate
        && matches!(
            state.reaction,
            MascotReaction::Casting | MascotReaction::Refreshing
        )
    {
        let ripple_r = 0.18 + state.reaction_progress.clamp(0.0, 1.0) * 0.82;
        if (radius - ripple_r).abs() <= 0.032 {
            let glyph = if (x + y).is_multiple_of(2) {
                "✦"
            } else {
                "✧"
            };
            if is_mono {
                return Some((glyph, Style::default().add_modifier(Modifier::DIM)));
            }
            return Some((
                glyph,
                Style::default()
                    .fg(Color::Rgb(accent_rgb.0, accent_rgb.1, accent_rgb.2))
                    .add_modifier(Modifier::BOLD),
            ));
        }
    }

    let rot_mult = match state.reaction {
        MascotReaction::Casting | MascotReaction::Refreshing => 2.8,
        MascotReaction::Scrying => 1.6,
        _ => 1.0,
    };

    // 1. Concentric counter-rotating arcane rune rings (filling wide side margins & outer corners)
    let rings: [(f32, f32, f32, usize); 3] = [
        (0.47, 0.020, 1.0, 18),
        (0.68, 0.022, -0.75, 24),
        (0.92, 0.024, 0.55, 32),
    ];
    for (ring_idx, &(r_target, thickness, speed_dir, slots)) in rings.iter().enumerate() {
        let dist = (radius - r_target).abs();
        if dist <= thickness {
            let rot = if can_animate {
                now_ms * 0.00042 * speed_dir * rot_mult
            } else {
                0.0
            };
            let norm_angle =
                ((angle + rot).rem_euclid(std::f32::consts::TAU)) / std::f32::consts::TAU;
            let slot_f = norm_angle * (slots as f32);
            let slot_idx = slot_f.floor() as usize;
            let slot_frac = slot_f - (slot_idx as f32);

            let is_rune_node = slot_frac < 0.28;
            let glyph = if is_rune_node {
                ARCANE_RING_RUNES[(slot_idx + ring_idx * 3) % ARCANE_RING_RUNES.len()]
            } else if (slot_idx + ring_idx).is_multiple_of(2) {
                "·"
            } else {
                "∶"
            };

            if is_mono {
                return Some((glyph, Style::default().add_modifier(Modifier::DIM)));
            }
            let pulse = if can_animate {
                ((now_ms * 0.003 + (slot_idx as f32) * 0.7).sin() * 0.5 + 0.5).clamp(0.0, 1.0)
            } else {
                0.6
            };
            let color = if can_animate && state.reaction == MascotReaction::Startled {
                Color::Rgb(
                    lerp_u8(border_rgb.0, warn_rgb.0, 0.55 + pulse * 0.40),
                    lerp_u8(border_rgb.1, warn_rgb.1, 0.55 + pulse * 0.40),
                    lerp_u8(border_rgb.2, warn_rgb.2, 0.55 + pulse * 0.40),
                )
            } else if is_rune_node && slot_idx.is_multiple_of(2) {
                Color::Rgb(
                    lerp_u8(border_rgb.0, accent_rgb.0, 0.45 + pulse * 0.45),
                    lerp_u8(border_rgb.1, accent_rgb.1, 0.45 + pulse * 0.45),
                    lerp_u8(border_rgb.2, accent_rgb.2, 0.45 + pulse * 0.45),
                )
            } else {
                Color::Rgb(
                    lerp_u8(muted_rgb.0, border_rgb.0, 0.35 + pulse * 0.50),
                    lerp_u8(muted_rgb.1, border_rgb.1, 0.35 + pulse * 0.50),
                    lerp_u8(muted_rgb.2, border_rgb.2, 0.35 + pulse * 0.50),
                )
            };
            let mut style = Style::default().fg(color);
            if !is_rune_node || pulse < 0.72 {
                style = style.add_modifier(Modifier::DIM);
            }
            return Some((glyph, style));
        }
    }

    // 2. Drifting mana motes & twinkling arcane starfield across open night sky
    let drift_steps = if can_animate {
        (now_ms / 420.0).floor() as u64
    } else {
        0
    };
    let cell_hash = (x as u64).wrapping_mul(0x9E37_79B9_7F4A_7C15).wrapping_add(
        (y as u64)
            .wrapping_add(drift_steps)
            .wrapping_mul(0xBF58_476D_1CE4_E5B9),
    ) ^ 0x94D0_49BB_1331_11EB;

    if cell_hash.is_multiple_of(23) {
        let idx = ((cell_hash >> 8) as usize) % ARCANE_MOTE_GLYPHS.len();
        let glyph = ARCANE_MOTE_GLYPHS[idx];
        if is_mono {
            return Some((glyph, Style::default().add_modifier(Modifier::DIM)));
        }
        let phase = ((cell_hash >> 16) & 0xFF) as f32 * 0.04;
        let twinkle = if can_animate {
            ((now_ms * 0.0038 + phase).sin() * 0.5 + 0.5).clamp(0.0, 1.0)
        } else {
            0.55
        };
        let is_gold_mote = idx >= 4;
        let (r, g, b) = if can_animate && state.reaction == MascotReaction::Startled {
            (
                lerp_u8(muted_rgb.0, warn_rgb.0, 0.40 + twinkle * 0.55),
                lerp_u8(muted_rgb.1, warn_rgb.1, 0.40 + twinkle * 0.55),
                lerp_u8(muted_rgb.2, warn_rgb.2, 0.40 + twinkle * 0.55),
            )
        } else if is_gold_mote {
            (
                lerp_u8(muted_rgb.0, accent_rgb.0, 0.30 + twinkle * 0.65),
                lerp_u8(muted_rgb.1, accent_rgb.1, 0.30 + twinkle * 0.65),
                lerp_u8(muted_rgb.2, accent_rgb.2, 0.30 + twinkle * 0.65),
            )
        } else {
            (
                lerp_u8(muted_rgb.0, border_rgb.0, 0.25 + twinkle * 0.65),
                lerp_u8(muted_rgb.1, border_rgb.1, 0.25 + twinkle * 0.65),
                lerp_u8(muted_rgb.2, border_rgb.2, 0.25 + twinkle * 0.65),
            )
        };
        let mut style = Style::default().fg(Color::Rgb(r, g, b));
        if twinkle < 0.78 {
            style = style.add_modifier(Modifier::DIM);
        }
        return Some((glyph, style));
    }

    None
}

/// Renders the full-screen Riverflow spellcaster Unicode Braille (`⠁..⣿`) canvas in
/// aspect-ratio-preserved **True-Color RGB** when Background-Only (`ui.hide_ui`) mode is active,
/// surrounded by animated concentric arcane rune circles and drifting mana motes across all open space.
pub fn render_fullscreen_background_canvas(
    buf: &mut ratatui::buffer::Buffer,
    area: Rect,
    anim_elapsed: Duration,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) {
    render_fullscreen_background_canvas_with_state(
        buf,
        area,
        anim_elapsed,
        MascotAnimState::default(),
        animations_enabled,
        mono,
        theme,
    );
}

/// Renders the full-screen Riverflow spellcaster canvas with regional gaze, blink, and arcane backdrop reactions.
pub fn render_fullscreen_background_canvas_with_state(
    buf: &mut ratatui::buffer::Buffer,
    area: Rect,
    anim_elapsed: Duration,
    state: MascotAnimState,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) {
    if area.width < 10 || area.height < 6 {
        return;
    }
    let is_mono = mono || theme.mono;
    let can_animate = animations_enabled && !is_mono && !anim_elapsed.is_zero();
    let elapsed_ms = anim_elapsed.as_millis() as u64;
    let now_ms = anim_elapsed.as_secs_f32() * 1000.0;

    let reveal = if can_animate && elapsed_ms < 1400 {
        (now_ms / 1400.0).clamp(0.24, 1.0)
    } else {
        1.0
    };

    // Preserve the natural 80:32 (2.5:1) cell aspect ratio on wide viewports so facial features never stretch
    let ideal_w = ((area.height as f32) * (80.0 / 32.0)).round() as u16;
    let canvas_w = area.width.min(ideal_w.max(area.width.min(80))).max(10);
    let canvas_h = area.height;
    let canvas_x = area.x + area.width.saturating_sub(canvas_w) / 2;
    let canvas_y = area.y;

    let flow_speed = 0.20_f32;
    let flow_frequency = 0.32_f32;
    let flow_strength_sub = 0.85_f32;
    let direction_x = (20.0_f32.to_radians()).cos();
    let direction_y = (20.0_f32.to_radians()).sin();

    let target_cols = canvas_w as usize;
    let target_rows = canvas_h as usize;
    let h = canvas_h.saturating_sub(1).max(1) as f32;
    let full_w = area.width.saturating_sub(1).max(1) as f32;
    let full_h = area.height.saturating_sub(1).max(1) as f32;
    let is_blinking = can_animate && is_mascot_blinking(elapsed_ms, state.reaction);
    let has_gaze_offset = can_animate && (state.gaze_x.abs() > 0.02 || state.gaze_y.abs() > 0.02);
    let pupil_col = (37.0 + state.gaze_x * 1.8).round() as usize;
    let pupil_row = (6.5 + state.gaze_y * 0.9).round().clamp(5.0, 8.0) as usize;

    for y in area.y..area.y.saturating_add(area.height) {
        let row = (y - canvas_y) as usize;
        let rel_y = row as f32 / h;
        let mapped_row = ((rel_y * 31.0).round() as usize).min(31);
        let glitch_shift = if can_animate {
            compute_glitch_band_shift(mapped_row % 8, elapsed_ms)
        } else {
            0
        };

        for x in area.x..area.x.saturating_add(area.width) {
            let Some(cell) = buf.cell_mut((x, y)) else {
                continue;
            };
            let screen_dx = (x - area.x) as f32 / full_w - 0.5;
            let screen_dy = (y - area.y) as f32 / full_h - 0.5;
            if screen_dx.hypot(screen_dy) > reveal * 0.78 {
                cell.set_symbol(" ");
                cell.set_style(Style::default());
                continue;
            }

            let in_portrait_bounds =
                x >= canvas_x && x < canvas_x.saturating_add(canvas_w) && y >= canvas_y;
            if in_portrait_bounds {
                let col = (x - canvas_x) as usize;
                let mapped_col = (col * 80) / target_cols.max(1);
                let in_face = (5..=8).contains(&mapped_row) && (34..=41).contains(&mapped_col);
                let in_spell_focus =
                    (5..=14).contains(&mapped_row) && (62..=76).contains(&mapped_col);

                let mut sub_shift_x = -(glitch_shift as f32) * 2.0;
                let mut sub_shift_y = 0.0_f32;
                let mut wave_mod = 0.0_f32;

                if can_animate {
                    let phase = (col as f32 * direction_x + row as f32 * 2.0 * direction_y)
                        * flow_frequency
                        + now_ms * flow_speed * std::f32::consts::PI * 0.002;
                    let drift = phase.sin() * flow_strength_sub;
                    sub_shift_x -= direction_x * drift;
                    sub_shift_y -= (direction_y * drift) * 0.5;
                    wave_mod = phase.sin() * 0.10;

                    if in_face {
                        sub_shift_x -= state.gaze_x * 2.2;
                        sub_shift_y -= state.gaze_y * 1.8;
                    }
                    if in_spell_focus {
                        sub_shift_y += (now_ms * 0.0042).sin() * 2.0;
                        if matches!(
                            state.reaction,
                            MascotReaction::Casting | MascotReaction::Refreshing
                        ) {
                            sub_shift_y -=
                                (state.reaction_progress * std::f32::consts::PI).sin() * 3.0;
                            wave_mod += 0.25;
                        }
                    }
                }

                let (mut sr, mut sg, mut sb, mut ch) = sample_braille_cell(
                    &RIVERFLOW_BRAILLE_80X32,
                    col,
                    row,
                    target_cols,
                    target_rows,
                    sub_shift_x,
                    sub_shift_y,
                );
                if can_animate && ch != ' ' && in_face {
                    if is_blinking && mapped_row == 6 && (35..=39).contains(&mapped_col) {
                        ch = '\u{2812}';
                        sr = 236;
                        sg = 185;
                        sb = 170;
                    } else if has_gaze_offset && mapped_col == pupil_col && mapped_row == pupil_row
                    {
                        ch = carve_gaze_pupil_in_braille(ch, state.gaze_x, state.gaze_y);
                        wave_mod -= 0.16;
                    }
                }

                if ch != ' ' {
                    let mut buf_char = [0u8; 4];
                    let sym = ch.encode_utf8(&mut buf_char);
                    cell.set_symbol(sym);
                    if is_mono {
                        cell.set_style(Style::default());
                    } else {
                        // Dual-Layer Shading (Layer B): vivid True-Color RGB with subtle theme harmony
                        let glitch_boost = if glitch_shift != 0 { 0.12 } else { 0.0 };
                        let fg_color = resolve_truecolor_mascot_cell(
                            theme,
                            (sr, sg, sb),
                            wave_mod + glitch_boost,
                        );
                        let luma =
                            (sr as f32 * 0.2126 + sg as f32 * 0.7152 + sb as f32 * 0.0722) / 255.0;
                        let mut style = Style::default().fg(fg_color);
                        if luma >= 0.74 || glitch_shift != 0 {
                            style = style.add_modifier(Modifier::BOLD);
                        }
                        cell.set_style(style);
                    }
                    continue;
                }
            }

            // Fill surrounding blank space (side margins & night sky corners) with animated arcane runes & mana motes
            if let Some((sym, style)) =
                sample_arcane_backdrop_cell(x, y, area, now_ms, state, can_animate, is_mono, theme)
            {
                cell.set_symbol(sym);
                cell.set_style(style);
            } else {
                cell.set_symbol(" ");
                cell.set_style(Style::default());
            }
        }
    }
}

