    fn chibi_companion_renders_gaze_directions_and_action_reactions() {
        let indigo = Theme::with_theme(ThemeName::Indigo, false);

        let gaze_left = render_chibi_companion_with_state(
            CompanionMood::Normal,
            1,
            MascotAnimState {
                gaze_x: -0.65,
                ..Default::default()
            },
            true,
            false,
            &indigo,
        );
        let gaze_right = render_chibi_companion_with_state(
            CompanionMood::Normal,
            1,
            MascotAnimState {
                gaze_x: 0.65,
                ..Default::default()
            },
            true,
            false,
            &indigo,
        );
        let casting =
            render_chibi_companion_with_tick(CompanionMood::Casting, 1, true, false, &indigo);
        let refreshing =
            render_chibi_companion_with_tick(CompanionMood::Refreshing, 1, true, false, &indigo);

        assert!(lines_to_string(&gaze_left).contains("*=[‹‿‹]=*"));
        assert!(lines_to_string(&gaze_right).contains("*=[›‿›]=*"));
        assert!(lines_to_string(&casting).contains("*=[✧‿<]=*"));
        assert!(lines_to_string(&casting).contains("/| 🌻✦|\\"));
        assert!(lines_to_string(&refreshing).contains("*=[✦‿✦]=*"));
        assert!(lines_to_string(&refreshing).contains("/↻\\"));
    }
