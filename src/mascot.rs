/// Computes perceptual luminance + contrast/brightness/threshold + 4x4 Bayer dithering.
pub fn compute_dithered_luminance(r: u8, g: u8, b: u8, row: usize, col: usize) -> f32 {
    let contrast = 1.1_f32;
    let brightness_boost = 2.0_f32;
    let threshold = 0.06_f32;
    let dither_strength = 0.8_f32;
    let posterize_steps = 32.0_f32;

    let raw_lum = (r as f32 * 0.2126 + g as f32 * 0.7152 + b as f32 * 0.0722) / 255.0;
    let contrasted = ((raw_lum - 0.5) * contrast + 0.5).clamp(0.0, 1.0);
    let boosted = (contrasted * brightness_boost).clamp(0.0, 1.0);
    let thresholded = if boosted <= threshold {
        0.0
    } else {
        (boosted - threshold) / (1.0 - threshold)
    };

    let bayer_val = BAYER_4X4[(row % 4) * 4 + (col % 4)];
    let bayer_dithered =
        (thresholded + ((bayer_val / 16.0 - 0.5) * dither_strength) / 4.0).clamp(0.0, 1.0);

    let quantized = ((bayer_dithered * (posterize_steps - 1.0)).round()) / (posterize_steps - 1.0);
    (bayer_dithered + (quantized - bayer_dithered) * 0.5).clamp(0.0, 1.0)
}

/// Maps a normalized `[0.0, 1.0]` luminance value to a character from `MAGA_ASCII_CHARS`.
pub fn luminance_to_ascii_char(value: f32) -> char {
    let clamped = value.clamp(0.0, 1.0);
    let max_idx = (MAGA_ASCII_CHARS.len() - 1) as f32;
    let idx = (clamped * max_idx).floor() as usize;
    MAGA_ASCII_CHARS[idx.min(MAGA_ASCII_CHARS.len() - 1)] as char
}

fn extract_rgb(style: Style, fallback: (u8, u8, u8)) -> (u8, u8, u8) {
    match style.fg {
        Some(Color::Rgb(r, g, b)) => (r, g, b),
        _ => fallback,
    }
}

fn lerp_u8(a: u8, b: u8, t: f32) -> u8 {
    let t = t.clamp(0.0, 1.0);
    (a as f32 + (b as f32 - a as f32) * t).round() as u8
}

/// Interpolates across a 3-stop theme gradient (`muted` -> `active_border` -> `accent`)
/// and blends source pixel highlights (sunflower gold `#F4B942` and white cat-eye frames `#F0EEFF`).
pub fn resolve_mascot_cell_color(theme: &Theme, source_rgb: (u8, u8, u8), value: f32) -> Color {
    let c0 = extract_rgb(theme.muted, (122, 114, 166));
    let c1 = extract_rgb(theme.active_border, (124, 106, 242));
    let c2 = extract_rgb(theme.accent, (244, 185, 66));

    let pos = value.clamp(0.0, 1.0) * 2.0;
    let (grad_r, grad_g, grad_b) = if pos < 1.0 {
        (
            lerp_u8(c0.0, c1.0, pos),
            lerp_u8(c0.1, c1.1, pos),
            lerp_u8(c0.2, c1.2, pos),
        )
    } else {
        let mix = pos - 1.0;
        (
            lerp_u8(c1.0, c2.0, mix),
            lerp_u8(c1.1, c2.1, mix),
            lerp_u8(c1.2, c2.2, mix),
        )
    };

    let (sr, sg, sb) = source_rgb;
    let is_gold = sr >= 210 && sg >= 165 && sb <= 110;
    let is_glasses_or_smile = sr >= 230 && sg >= 228 && sb >= 245;

    if is_gold {
        // Preserve iconic sunflower gold crest/clasp/wand while tinting slightly toward theme accent
        Color::Rgb(
            lerp_u8(sr, c2.0, 0.25),
            lerp_u8(sg, c2.1, 0.25),
            lerp_u8(sb, c2.2, 0.25),
        )
    } else if is_glasses_or_smile {
        // Keep cat-eye glasses & smile crisp and luminous
        let base_fg = extract_rgb(theme.base, (240, 238, 255));
        Color::Rgb(
            lerp_u8(sr, base_fg.0, 0.35),
            lerp_u8(sg, base_fg.1, 0.35),
            lerp_u8(sb, base_fg.2, 0.35),
        )
    } else {
        // Blend 70% theme gradient with 30% source RGB for rich depth
        Color::Rgb(
            lerp_u8(grad_r, sr, 0.30),
            lerp_u8(grad_g, sg, 0.30),
            lerp_u8(grad_b, sb, 0.30),
        )
    }
}

/// Resolves True-Color RGB shading (`Option 3`) for the Unicode Braille Hero and Background-Only
/// canvases, preserving 82% of the authentic artwork RGB colors (warm skin tones, white cat-eye frames,
/// sunflower gold petals, rose/indigo robes, and glowing runes) harmonized with 18% of the active theme.
pub fn resolve_truecolor_mascot_cell(
    theme: &Theme,
    source_rgb: (u8, u8, u8),
    wave_luma_mod: f32,
) -> Color {
    let (sr, sg, sb) = source_rgb;
    let raw_lum = (sr as f32 * 0.2126 + sg as f32 * 0.7152 + sb as f32 * 0.0722) / 255.0;
    let themed =
        resolve_mascot_cell_color(theme, source_rgb, (raw_lum + wave_luma_mod).clamp(0.0, 1.0));
    let (tr, tg, tb) = match themed {
        Color::Rgb(r, g, b) => (r, g, b),
        _ => (sr, sg, sb),
    };
    let boost = 1.0 + wave_luma_mod * 0.65;
    let r = (lerp_u8(sr, tr, 0.18) as f32 * boost)
        .round()
        .clamp(0.0, 255.0) as u8;
    let g = (lerp_u8(sg, tg, 0.18) as f32 * boost)
        .round()
        .clamp(0.0, 255.0) as u8;
    let b = (lerp_u8(sb, tb, 0.18) as f32 * boost)
        .round()
        .clamp(0.0, 255.0) as u8;
    Color::Rgb(r, g, b)
}

/// Deterministic scanline glitch band offset for a given row and elapsed millisecond timestamp.
/// Matches `ascii-effect.tsx` (`glitchFrequency = 1.4`, ~714ms period, ~120ms active glitch window).
fn compute_glitch_band_shift(row: usize, elapsed_ms: u64) -> isize {
    if elapsed_ms == 0 {
        return 0;
    }
    let period_ms = 714_u64;
    let window_pos = elapsed_ms % period_ms;
    if window_pos > 120 {
        return 0;
    }
    let bucket = elapsed_ms / period_ms;
    let hash = bucket
        .wrapping_mul(0x9E37_79B9_7F4A_7C15)
        .wrapping_add((row as u64).wrapping_mul(0xBF58_476D_1CE4_E5B9));
    let glitch_row_a = (bucket.wrapping_mul(3) as usize) % 8;
    let glitch_row_b = (bucket.wrapping_mul(5).wrapping_add(2) as usize) % 8;
    if row == glitch_row_a || row == glitch_row_b {
        if hash & 1 == 0 { 1 } else { -1 }
    } else {
        0
    }
}

/// Builds the 8-row visual portrait for the `COMPANION · Maga` panel in `rich` mode
/// using the arcane ASCII shader pipeline (` .:-=+*#%@` density ramp, Bayer 4x4 dithering,
/// sine-wave `flow` displacement, radial startup `reveal`, and scanline `glitch` bands).
/// Automatically degrades to static or monochrome ASCII when `animations_enabled` is false or `theme.mono` is true.
pub fn build_rich_portrait_lines(
    theme: &Theme,
    _anim_tick: usize,
    animations_enabled: bool,
) -> Vec<Line<'static>> {
    build_rich_portrait_lines_with_elapsed(theme, Duration::ZERO, animations_enabled)
}

/// Builds the 8-row arcane ASCII portrait driven by continuous `anim_elapsed` time.
pub fn build_rich_portrait_lines_with_elapsed(
    theme: &Theme,
    anim_elapsed: Duration,
    animations_enabled: bool,
) -> Vec<Line<'static>> {
    let columns = 20_usize;
    let rows = 8_usize;
    let can_animate = animations_enabled && !theme.mono && !anim_elapsed.is_zero();
    let elapsed_ms = anim_elapsed.as_millis() as u64;
    let now_ms = anim_elapsed.as_secs_f32() * 1000.0;

    // Radial startup reveal (`revealDuration = 1400ms` in `ascii-effect.tsx`)
    let reveal = if can_animate && elapsed_ms < 1400 {
        (now_ms / 1400.0).clamp(0.28, 1.0)
    } else {
        1.0
    };

    // Directional sine-wave flow parameters adapted from `ascii-effect.tsx`
    let flow_speed = 0.22_f32;
    let flow_frequency = 0.42_f32;
    let flow_strength = 0.85_f32;
    let direction_x = (22.0_f32.to_radians()).cos();
    let direction_y = (22.0_f32.to_radians()).sin();

    let mut lines = Vec::with_capacity(rows);
    for row in 0..rows {
        let glitch_shift = if can_animate {
            compute_glitch_band_shift(row, elapsed_ms)
        } else {
            0
        };

        let mut spans = Vec::with_capacity(columns + 2);
        spans.push(Span::raw(" "));

        for col in 0..columns {
            let dx = (col as f32) / ((columns - 1) as f32) - 0.5;
            let dy = (row as f32) / ((rows - 1) as f32) - 0.5;
            if dx.hypot(dy) > reveal * 0.72 {
                spans.push(Span::raw(" "));
                continue;
            }

            let mut source_col = (col as isize - glitch_shift) as f32;
            let mut source_row = row as f32;
            let mut wave_luma_mod = 0.0_f32;

            if can_animate {
                let x = col as f32;
                let y = row as f32 * 2.0; // account for 1:2 terminal cell aspect ratio
                let phase = (x * direction_x + y * direction_y) * flow_frequency
                    + now_ms * flow_speed * std::f32::consts::PI * 0.002;
                let drift = phase.sin() * flow_strength;
                source_col -= direction_x * drift;
                source_row -= (direction_y * drift) * 0.35;
                wave_luma_mod = phase.sin() * 0.11;
            }

            let sampled_col =
                (source_col.round() as isize).clamp(0, (columns - 1) as isize) as usize;
            let sampled_row = (source_row.round() as isize).clamp(0, (rows - 1) as isize) as usize;
            let (sr, sg, sb) = MASCOT_PIXELS_20X8[sampled_row][sampled_col];

            let base_lum = compute_dithered_luminance(sr, sg, sb, sampled_row, sampled_col);
            let glitch_boost = if glitch_shift != 0 { 0.14 } else { 0.0 };
            let value = (base_lum + wave_luma_mod + glitch_boost).clamp(0.0, 1.0);
            let ch = luminance_to_ascii_char(value);

            if ch == ' ' {
                spans.push(Span::raw(" "));
            } else if theme.mono {
                spans.push(Span::raw(ch.to_string()));
            } else {
                let fg_color = resolve_mascot_cell_color(theme, (sr, sg, sb), value);
                let mut style = Style::default().fg(fg_color);
                if value >= 0.78 || glitch_shift != 0 {
                    style = style.add_modifier(Modifier::BOLD);
                }
                spans.push(Span::styled(ch.to_string(), style));
            }
        }

        spans.push(Span::raw(" "));
        lines.push(Line::from(spans));
    }

    lines
}

