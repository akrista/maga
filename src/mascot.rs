/// Renders the high-resolution (`54x22`) Hero Mascot Showcase with regional sub-pixel rigging
/// for eye gaze, periodic/reaction blinks, cat-eye glasses specular sweep, and floating sunflower wand.
pub fn render_hero_mascot_lines_with_state(
    width: u16,
    height: u16,
    anim_elapsed: Duration,
    state: MascotAnimState,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) -> Vec<Line<'static>> {
    let full_cols = (width as usize).max(16);
    let full_rows = (height as usize).max(8);
    let is_mono = mono || theme.mono;
    let can_animate = animations_enabled && !is_mono && !anim_elapsed.is_zero();
    let elapsed_ms = anim_elapsed.as_millis() as u64;
    let now_ms = anim_elapsed.as_secs_f32() * 1000.0;

    let reveal = if can_animate && elapsed_ms < 1400 {
        (now_ms / 1400.0).clamp(0.22, 1.0)
    } else {
        1.0
    };

    // Preserve the 54:22 cell aspect ratio while centering inside (full_cols, full_rows)
    let ideal_cols = ((full_rows as f32) * (54.0 / 22.0)).round() as usize;
    let portrait_cols = full_cols.min(ideal_cols.max(full_cols.min(54))).max(16);
    let ideal_rows = ((portrait_cols as f32) * (22.0 / 54.0)).round() as usize;
    let portrait_rows = full_rows.min(ideal_rows.max(full_rows.min(22))).max(8);
    let offset_x = full_cols.saturating_sub(portrait_cols) / 2;
    let offset_y = full_rows.saturating_sub(portrait_rows) / 2;
    let local_area = Rect::new(0, 0, full_cols as u16, full_rows as u16);

    let flow_speed = 0.22_f32;
    let flow_frequency = 0.34_f32;
    // Gentle sub-pixel flow (0.85 sub-pixels = ~0.42 cells) so Braille contours stay crisp while animating
    let flow_strength_sub = 0.85_f32;
    let direction_x = (22.0_f32.to_radians()).cos();
    let direction_y = (22.0_f32.to_radians()).sin();

    let is_blinking = can_animate && is_mascot_blinking(elapsed_ms, state.reaction);
    let has_gaze_offset = can_animate && (state.gaze_x.abs() > 0.02 || state.gaze_y.abs() > 0.02);
    let left_pupil_col = (22.5 + state.gaze_x * 1.6).round() as usize;
    let right_pupil_col = (31.5 + state.gaze_x * 1.6).round() as usize;
    let pupil_row = (10.0 + state.gaze_y * 0.85).round().clamp(9.0, 11.0) as usize;
    let glint_speed = match state.reaction {
        MascotReaction::Casting | MascotReaction::Scrying => 0.026,
        _ => 0.011,
    };
    let glint_band = 18 + ((now_ms * glint_speed) as usize % 36);

    let mut lines = Vec::with_capacity(full_rows);
    for row in 0..full_rows {
        let in_y = row >= offset_y && row < offset_y + portrait_rows;
        let p_row = row.saturating_sub(offset_y);
        let mapped_row = (p_row * 22) / portrait_rows.max(1);
        let glitch_shift = if can_animate && in_y {
            compute_glitch_band_shift(mapped_row % 8, elapsed_ms)
        } else {
            0
        };

        let mut spans = Vec::with_capacity(full_cols);
        for col in 0..full_cols {
            let dx = (col as f32) / ((full_cols.saturating_sub(1).max(1)) as f32) - 0.5;
            let dy = (row as f32) / ((full_rows.saturating_sub(1).max(1)) as f32) - 0.5;
            if dx.hypot(dy) > reveal * 0.76 {
                spans.push(Span::raw(" "));
                continue;
            }

            let in_x = col >= offset_x && col < offset_x + portrait_cols;
            if in_x && in_y {
                let p_col = col - offset_x;
                let mapped_col = (p_col * 54) / portrait_cols.max(1);
                let in_left_eye = (9..=11).contains(&mapped_row) && (20..=24).contains(&mapped_col);
                let in_right_eye =
                    (9..=11).contains(&mapped_row) && (30..=34).contains(&mapped_col);
                let in_glasses = (8..=11).contains(&mapped_row) && (18..=36).contains(&mapped_col);
                let in_wand = (8..=15).contains(&mapped_row) && (42..=51).contains(&mapped_col);

                let mut sub_shift_x = -(glitch_shift as f32) * 2.0;
                let mut sub_shift_y = 0.0_f32;
                let mut wave_luma_mod = 0.0_f32;

                if can_animate {
                    let x = p_col as f32;
                    let y = (p_row as f32) * 2.0;
                    let phase = (x * direction_x + y * direction_y) * flow_frequency
                        + now_ms * flow_speed * std::f32::consts::PI * 0.002;
                    let drift = phase.sin() * flow_strength_sub;
                    sub_shift_x -= direction_x * drift;
                    sub_shift_y -= (direction_y * drift) * 0.5;
                    wave_luma_mod = phase.sin() * 0.10;

                    if in_left_eye || in_right_eye {
                        sub_shift_x -= state.gaze_x * 2.4;
                        sub_shift_y -= state.gaze_y * 2.0;
                    }
                    if in_glasses && (mapped_col + mapped_row * 2).abs_diff(glint_band) <= 1 {
                        wave_luma_mod += 0.24;
                    }
                    if in_wand {
                        let wand_bob = (now_ms * 0.0045).sin() * 2.2;
                        let cast_recoil = if state.reaction == MascotReaction::Casting {
                            wave_luma_mod += 0.28 * (1.0 - state.reaction_progress * 0.5);
                            (state.reaction_progress * std::f32::consts::PI).sin() * 3.2
                        } else {
                            0.0
                        };
                        sub_shift_y += wand_bob - cast_recoil;
                    }
                }

                let (mut sr, mut sg, mut sb, mut ch) = sample_braille_cell(
                    &MASCOT_HERO_BRAILLE_54X22,
                    p_col,
                    p_row,
                    portrait_cols,
                    portrait_rows,
                    sub_shift_x,
                    sub_shift_y,
                );

                if can_animate && ch != ' ' && (in_left_eye || in_right_eye) {
                    let wink_right = state.reaction == MascotReaction::Casting && in_right_eye;
                    if is_blinking || wink_right {
                        if mapped_row == 10 {
                            ch = '\u{2812}'; // '⠒' closed horizontal eyelid
                            sr = 218;
                            sg = 198;
                            sb = 244;
                        } else {
                            ch = '\u{2824}'; // '⠤' softened lash line
                            wave_luma_mod -= 0.16;
                        }
                    } else if state.reaction == MascotReaction::Casting
                        && in_left_eye
                        && mapped_row == 10
                        && mapped_col == 22
                    {
                        ch = '\u{289B}'; // crisp starlight iris catchlight
                        sr = 255;
                        sg = 216;
                        sb = 92;
                        wave_luma_mod += 0.30;
                    } else if has_gaze_offset {
                        let target_col = if in_left_eye {
                            left_pupil_col
                        } else {
                            right_pupil_col
                        };
                        if mapped_col == target_col && mapped_row == pupil_row {
                            ch = carve_gaze_pupil_in_braille(ch, state.gaze_x, state.gaze_y);
                            wave_luma_mod -= 0.18;
                        }
                    }
                }

                if ch != ' ' {
                    if is_mono {
                        spans.push(Span::raw(ch.to_string()));
                    } else {
                        let glitch_boost = if glitch_shift != 0 { 0.12 } else { 0.0 };
                        let fg_color = resolve_truecolor_mascot_cell(
                            theme,
                            (sr, sg, sb),
                            wave_luma_mod + glitch_boost,
                        );
                        let luma =
                            (sr as f32 * 0.2126 + sg as f32 * 0.7152 + sb as f32 * 0.0722) / 255.0;
                        let mut style = Style::default().fg(fg_color);
                        if luma >= 0.74 || glitch_shift != 0 {
                            style = style.add_modifier(Modifier::BOLD);
                        }
                        spans.push(Span::styled(ch.to_string(), style));
                    }
                    continue;
                }
            }

            // Fill surrounding blank space in Hero Showcase with animated arcane rune rings & mana motes
            if let Some((sym, style)) = sample_arcane_backdrop_cell(
                col as u16,
                row as u16,
                local_area,
                now_ms,
                state,
                can_animate,
                is_mono,
                theme,
            ) {
                spans.push(Span::styled(sym, style));
            } else {
                spans.push(Span::raw(" "));
            }
        }
        lines.push(Line::from(spans));
    }

    lines
}

