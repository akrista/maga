/// Action-driven reaction state for Maga across Hero Showcase, Background, and Chibi Companion.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub enum MascotReaction {
    #[default]
    Idle,
    Casting,
    Scrying,
    Refreshing,
    Startled,
}

/// Real-time animation, gaze, and reaction state passed to Maga's 3-tier renderers.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct MascotAnimState {
    pub gaze_x: f32,
    pub gaze_y: f32,
    pub last_input_elapsed: Duration,
    pub reaction: MascotReaction,
    pub reaction_progress: f32,
}

/// Mood state for the compact Moe / Chibi Kaomoji witch companion (`COMPANION · Maga`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CompanionMood {
    Normal,
    Casting,
    Refreshing,
    Filtering,
    Conflict,
}

/// Determines the active `CompanionMood` from the current `App` state.
pub fn companion_mood_for_app(app: &App) -> CompanionMood {
    let active_filter = match app.section {
        WorkspaceSection::Mcps => !app.filter_query.is_empty(),
        WorkspaceSection::Plugins => !app.plugin_filter_query.is_empty(),
        _ => false,
    };
    if !app.outcome.conflicts.is_empty()
        || app
            .status_message
            .as_ref()
            .is_some_and(|(_, is_err)| *is_err)
        || app.mascot_reaction == MascotReaction::Startled
    {
        CompanionMood::Conflict
    } else if matches!(app.mode, ActiveMode::Filtering)
        || active_filter
        || app.mascot_reaction == MascotReaction::Scrying
    {
        CompanionMood::Filtering
    } else if app.mascot_reaction == MascotReaction::Casting {
        CompanionMood::Casting
    } else if app.mascot_reaction == MascotReaction::Refreshing {
        CompanionMood::Refreshing
    } else {
        CompanionMood::Normal
    }
}

/// Renders the compact (~14x5) Moe / Chibi Kaomoji witch companion with state-reactive expressions.
pub fn render_chibi_companion(
    mood: CompanionMood,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) -> Vec<Line<'static>> {
    render_chibi_companion_with_tick(mood, 0, animations_enabled, mono, theme)
}

/// Renders the compact (~14x5) Moe / Chibi Kaomoji witch companion with idle blink & sparkle ticks.
pub fn render_chibi_companion_with_tick(
    mood: CompanionMood,
    anim_tick: usize,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) -> Vec<Line<'static>> {
    render_chibi_companion_with_state(
        mood,
        anim_tick,
        MascotAnimState::default(),
        animations_enabled,
        mono,
        theme,
    )
}

/// Renders the compact (~14x5) Moe / Chibi Kaomoji witch companion with gaze, reactions, and blinks.
pub fn render_chibi_companion_with_state(
    mood: CompanionMood,
    anim_tick: usize,
    state: MascotAnimState,
    animations_enabled: bool,
    mono: bool,
    theme: &Theme,
) -> Vec<Line<'static>> {
    let can_animate = animations_enabled && !mono && !theme.mono;
    let sp1 = sparkle_glyph(anim_tick, can_animate, mono || theme.mono);
    let sp2 = sparkle_glyph(anim_tick.wrapping_add(2), can_animate, mono || theme.mono);
    let is_blink = can_animate && (anim_tick % 12 == 5);

    let hat_style = if mono || theme.mono {
        Style::default()
    } else {
        theme.active_border
    };
    let accent_style = if mono || theme.mono {
        Style::default()
    } else {
        theme.accent
    };
    let face_style = if mono || theme.mono {
        Style::default()
    } else {
        theme.bold
    };
    let muted_style = if mono || theme.mono {
        Style::default()
    } else {
        theme.muted
    };

    let (crest, face, badge_style, robe) = match mood {
        CompanionMood::Normal => {
            let eyes = if is_blink {
                "*=[-‿-]=*"
            } else if can_animate && state.gaze_x < -0.35 {
                "*=[‹‿‹]=*"
            } else if can_animate && state.gaze_x > 0.35 {
                "*=[›‿›]=*"
            } else {
                "*=[o‿o]=*"
            };
            ("/🌻\\", eyes, accent_style, "/| 🌻 |\\")
        }
        CompanionMood::Casting => ("/✦\\", "*=[✧‿<]=*", accent_style, "/| 🌻✦|\\"),
        CompanionMood::Refreshing => ("/↻\\", "*=[✦‿✦]=*", accent_style, "/| ✧🌻|\\"),
        CompanionMood::Filtering => ("/🔮\\", "*=[o_O]=?", accent_style, "/| ✧  |\\"),
        CompanionMood::Conflict => {
            let warn = if mono || theme.mono {
                Style::default()
            } else {
                theme.warning
            };
            ("/!!\\", "*=[>_<]=!", warn, "/| ⚡ |\\")
        }
    };

    vec![
        Line::from(vec![
            Span::styled(format!("  {sp1} "), accent_style),
            Span::styled("/▲\\", hat_style),
            Span::styled(format!(" {sp2}  "), accent_style),
        ]),
        Line::from(vec![
            Span::styled("  _/", hat_style),
            Span::styled(crest, badge_style),
            Span::styled("\\_ ", hat_style),
        ]),
        Line::from(vec![
            Span::raw("  "),
            Span::styled(face, face_style),
            Span::raw("  "),
        ]),
        Line::from(vec![
            Span::raw("   "),
            Span::styled(robe, accent_style),
            Span::raw("   "),
        ]),
        Line::from(vec![Span::styled("   '-----'   ", muted_style)]),
    ]
}

const BRAILLE_DOT_BITS: [(usize, usize, u8); 8] = [
    (0, 0, 0x01),
    (0, 1, 0x02),
    (0, 2, 0x04),
    (1, 0, 0x08),
    (1, 1, 0x10),
    (1, 2, 0x20),
    (0, 3, 0x40),
    (1, 3, 0x80),
];

fn braille_dot_bit(dx: usize, dy: usize) -> u8 {
    match (dx, dy) {
        (0, 0) => 0x01,
        (0, 1) => 0x02,
        (0, 2) => 0x04,
        (1, 0) => 0x08,
        (1, 1) => 0x10,
        (1, 2) => 0x20,
        (0, 3) => 0x40,
        (1, 3) => 0x80,
        _ => 0,
    }
}

fn is_mascot_blinking(elapsed_ms: u64, reaction: MascotReaction) -> bool {
    if reaction == MascotReaction::Startled {
        return (elapsed_ms % 260) < 110;
    }
    let cycle = elapsed_ms % 3600;
    let double_cycle = elapsed_ms % 7200;
    (3100..3240).contains(&cycle) || (3320..3440).contains(&double_cycle)
}

fn carve_gaze_pupil_in_braille(ch: char, gaze_x: f32, gaze_y: f32) -> char {
    let code = ch as u32;
    if !(0x2801..=0x28FF).contains(&code) {
        return ch;
    }
    let mask = (code - 0x2800) as u8;
    let dot_x = if gaze_x >= 0.0 { 1 } else { 0 };
    let dot_y = ((gaze_y.clamp(-1.0, 1.0) + 1.0) * 1.5)
        .round()
        .clamp(0.0, 3.0) as usize;
    let bit = braille_dot_bit(dot_x, dot_y);
    let carved = mask & !bit;
    if carved == 0 {
        ch
    } else {
        char::from_u32(0x2800 + carved as u32).unwrap_or(ch)
    }
}

/// Samples a `2x4` Unicode Braille character (`U+2801..U+28FF`) and average RGB color from a
/// precomputed Braille grid in continuous sub-pixel space (`COLS * 2` x `ROWS * 4`).
fn sample_braille_cell<const COLS: usize, const ROWS: usize>(
    grid: &[[(u8, u8, u8, u8); COLS]; ROWS],
    col: usize,
    row: usize,
    target_cols: usize,
    target_rows: usize,
    sub_shift_x: f32,
    sub_shift_y: f32,
) -> (u8, u8, u8, char) {
    if target_cols == COLS
        && target_rows == ROWS
        && sub_shift_x.abs() < 0.35
        && sub_shift_y.abs() < 0.35
    {
        let (r, g, b, mask) = grid[row.min(ROWS - 1)][col.min(COLS - 1)];
        if mask == 0 || (r, g, b) == (0, 0, 0) {
            return (0, 0, 0, ' ');
        }
        let ch = char::from_u32(0x2800 + mask as u32).unwrap_or(' ');
        return (r, g, b, ch);
    }

    let sub_w = COLS * 2;
    let sub_h = ROWS * 4;
    let denom_x = (target_cols * 2).saturating_sub(1).max(1) as f32;
    let denom_y = (target_rows * 4).saturating_sub(1).max(1) as f32;
    let scale_x = (sub_w - 1) as f32 / denom_x;
    let scale_y = (sub_h - 1) as f32 / denom_y;

    let mut out_mask = 0u8;
    let mut r_acc = 0u32;
    let mut g_acc = 0u32;
    let mut b_acc = 0u32;
    let mut cnt = 0u32;

    for &(dx, dy, bit) in &BRAILLE_DOT_BITS {
        let tx = (col * 2 + dx) as f32;
        let ty = (row * 4 + dy) as f32;
        let sx =
            ((tx * scale_x + sub_shift_x).round() as isize).clamp(0, (sub_w - 1) as isize) as usize;
        let sy =
            ((ty * scale_y + sub_shift_y).round() as isize).clamp(0, (sub_h - 1) as isize) as usize;

        let (sr, sg, sb, smask) = grid[sy / 4][sx / 2];
        if smask & braille_dot_bit(sx % 2, sy % 4) != 0 && (sr, sg, sb) != (0, 0, 0) {
            out_mask |= bit;
            r_acc += sr as u32;
            g_acc += sg as u32;
            b_acc += sb as u32;
            cnt += 1;
        }
    }

    if out_mask == 0 || cnt == 0 {
        (0, 0, 0, ' ')
    } else {
        let ch = char::from_u32(0x2800 + out_mask as u32).unwrap_or(' ');
        (
            (r_acc / cnt) as u8,
            (g_acc / cnt) as u8,
            (b_acc / cnt) as u8,
            ch,
        )
    }
}

