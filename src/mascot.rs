/// Builds the reactive status dialogue lines displayed beside the portrait in `COMPANION · Maga`.
pub fn build_companion_dialogue(app: &App, theme: &Theme, anim_tick: usize) -> Vec<Line<'static>> {
    let sp = sparkle_glyph(anim_tick, app.animations_enabled(), theme.mono);
    let total = app.outcome.canonical.len();
    let active = app.outcome.canonical.values().filter(|s| s.enabled).count();
    let (active_plugins, total_plugins) = app.total_plugins_counts();
    let conflicts = app.outcome.conflicts.len();

    let mut lines = Vec::new();
    lines.push(Line::from(vec![
        Span::styled(format!("{sp} "), theme.accent),
        Span::styled("Maga · Arcane MCP Weaver", theme.bold),
    ]));

    if conflicts > 0 {
        lines.push(Line::from(Span::styled(
            format!("! {conflicts} conflict(s) detected across harnesses."),
            theme.warning,
        )));
        lines.push(Line::from(Span::styled(
            "Press 'c' to weave a side-by-side resolution.",
            theme.muted,
        )));
    } else {
        match app.section {
            WorkspaceSection::Mcps => {
                if matches!(app.mode, ActiveMode::Filtering) || !app.filter_query.is_empty() {
                    let visible = app.visible_servers().len();
                    lines.push(Line::from(Span::styled(
                        format!("Scrying '/{}' → {visible} match(es).", app.filter_query),
                        theme.accent,
                    )));
                    lines.push(Line::from(Span::styled(
                        "Press Enter to keep or Esc to clear filter.",
                        theme.muted,
                    )));
                } else if let Some((ref msg, is_err)) = app.status_message {
                    let style = if is_err { theme.error } else { theme.success };
                    lines.push(Line::from(Span::styled(msg.clone(), style)));
                    lines.push(Line::from(Span::styled(
                        format!("{active}/{total} spells active · press 'o' for options."),
                        theme.muted,
                    )));
                } else if total == 0 {
                    lines.push(Line::from(Span::styled(
                        "Grimoire is empty — no MCP servers yet.",
                        theme.muted,
                    )));
                    lines.push(Line::from(Span::styled(
                        "Press 'a' to summon a new MCP server.",
                        theme.accent,
                    )));
                } else {
                    lines.push(Line::from(Span::styled(
                        format!("✓ {active}/{total} MCP spells harmonized!"),
                        theme.success,
                    )));
                    lines.push(Line::from(Span::styled(
                        format!("Targets: {}", app.enabled_harnesses_label()),
                        theme.muted,
                    )));
                }
            }
            WorkspaceSection::Plugins => {
                if matches!(app.mode, ActiveMode::Filtering) || !app.plugin_filter_query.is_empty()
                {
                    let visible = app
                        .visible_plugin_rows()
                        .iter()
                        .filter(|r| matches!(r, PluginRow::Plugin { .. }))
                        .count();
                    lines.push(Line::from(Span::styled(
                        format!(
                            "Scrying '/{}' → {visible} match(es).",
                            app.plugin_filter_query
                        ),
                        theme.accent,
                    )));
                    lines.push(Line::from(Span::styled(
                        "Press Enter to keep or Esc to clear filter.",
                        theme.muted,
                    )));
                } else if let Some((ref msg, is_err)) = app.status_message {
                    let style = if is_err { theme.error } else { theme.success };
                    lines.push(Line::from(Span::styled(msg.clone(), style)));
                    lines.push(Line::from(Span::styled(
                        format!(
                            "{active_plugins}/{total_plugins} plugins active · press 'o' for options."
                        ),
                        theme.muted,
                    )));
                } else if total_plugins == 0 {
                    lines.push(Line::from(Span::styled(
                        "No harness plugins discovered yet.",
                        theme.muted,
                    )));
                    lines.push(Line::from(Span::styled(
                        "Press 'o' to configure enabled harnesses.",
                        theme.accent,
                    )));
                } else {
                    lines.push(Line::from(Span::styled(
                        format!("✓ {active_plugins}/{total_plugins} harness plugins active!"),
                        theme.success,
                    )));
                    lines.push(Line::from(Span::styled(
                        format!("Targets: {}", app.enabled_harnesses_label()),
                        theme.muted,
                    )));
                }
            }
            _ => {}
        }
    }

    lines.push(Line::from(""));
    lines.push(Line::from(vec![
        Span::styled("Theme: ", theme.muted),
        Span::styled(app.loaded.config.ui.theme.as_str(), theme.accent),
        Span::styled(" · Mode: ", theme.muted),
        Span::styled(app.loaded.config.ui.mascot_mode.as_str(), theme.base),
        Span::styled(" · o: options", theme.muted),
    ]));

    lines
}

